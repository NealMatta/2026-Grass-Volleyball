#!/usr/bin/env node
/**
 * Generates docs/scoresheet.md from data/schedule.json + data/teams.json.
 *
 * The paper backup used to be hand-written, which meant every schedule change
 * silently left the printout describing a tournament that wasn't happening.
 * Same reasoning as docs/SCHEDULE.md: generate it, don't trust it.
 *
 * Run: node scripts/gen-scoresheet.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const { teams } = read('data/teams.json');
const schedule = read('data/schedule.json');
const t = schedule.tournament;
const pool = schedule.gameRules.pool;
const bracket = schedule.gameRules.bracket;

const name = (id) => teams.find((x) => x.id === id)?.name ?? id;
const BLANK = '____________';
const SCORE = '____';

const labelOf = (gameId) =>
  schedule.slots.flatMap((s) => s.games).find((g) => g.id === gameId)?.label ?? gameId.toUpperCase();

/** Render a bracket placeholder ({seed:1}, {winnerOf:'sf1'}) as human text. */
const side = (s) => {
  if (typeof s === 'string') return name(s);
  if (s.seed) return `#${s.seed}`;
  if (s.winnerOf) return `W ${labelOf(s.winnerOf)}`;
  if (s.loserOf) return `L ${labelOf(s.loserOf)}`;
  return '?';
};

const out = [];
const w = (s = '') => out.push(s);

const dateLabel = new Date(`${t.date}T12:00:00`).toLocaleDateString('en-US', {
  weekday: 'long',
  month: 'long',
  day: 'numeric',
});

w('<!-- GENERATED by scripts/gen-scoresheet.mjs — do not edit by hand. -->');
w('<!-- Edit data/schedule.json, run verify-schedule.mjs, then regenerate.  -->');
w();
w('# Score Sheet — Court ______');
w();
w(`**${t.name} · ${dateLabel} · ${t.venue}**`);
w();
w("Paper backup. Use this if the website isn't cooperating — cell signal at the lakefront isn't");
w('guaranteed and phones die. Hand it to Neal at the break.');
w();
w('**Write down BOTH scores, not just the winner.** Point differential is the third tiebreaker for');
w('bracket seeding.');
w();
w(`**Every team needs at least one woman on the court at all times.** Call it yourselves — if a`);
w('team can\'t field one, the point does not start.');
w();
w('---');
w();

// --- Pool, one table per court ------------------------------------------------
const poolSlots = schedule.slots.filter((s) => s.phase === 'pool');
w('## Pool play');
w();
for (let court = 1; court <= t.courts; court += 1) {
  w(`### Court ${court}`);
  w();
  w('| Slot | Time | Team A | Score | Team B | Score | Winner |');
  w('|:--|:--|:--|:--:|:--|:--:|:--|');
  for (const s of poolSlots) {
    const g = s.games.find((x) => x.court === court);
    if (!g) continue;
    w(
      `| ${s.slot} | ${s.time} | ${name(g.a)} | ${SCORE} | ${name(g.b)} | ${SCORE} | ${BLANK} |`
    );
  }
  w();
}
w(
  `Pool games: **to ${pool.to}**, win by ${pool.winBy}, cap ${pool.cap}. ` +
    `Slots start ${pool.slotMinutes} minutes apart.`
);
w();
w('---');
w();

// --- Standings worksheet ------------------------------------------------------
const breakNote = schedule.slots.find((s) => s.note)?.note;
const breakTime = breakNote?.match(/^([\d:]+)/)?.[1];
w(`## Standings worksheet${breakTime ? ` (${breakTime} break)` : ''}`);
w();
w('| Team | W | L | Points For | Points Against | Diff | Seed |');
w('|:--|:--:|:--:|:--:|:--:|:--:|:--:|');
for (const team of teams) w(`| ${team.name} | | | | | | |`);
w();
w(`**Tiebreakers, in order:** ${schedule.tiebreakers.map((x, i) => `${i + 1}. ${x}`).join(' → ')}`);
w();
w('---');
w();

// --- Bracket ------------------------------------------------------------------
w('## Bracket');
w();
if (bracket.bestOf) {
  // One line per team, a box per game, so the paper holds the real points even
  // though the site only records games won.
  w('| Slot | Time | Court | Match | Team | Game 1 | Game 2 | Game 3 | Games won |');
  w('|:--|:--|:--:|:--|:--|:--:|:--:|:--:|:--:|');
  for (const s of schedule.slots.filter((x) => x.phase === 'bracket')) {
    for (const g of s.games) {
      const label = `**${g.label}** — ${side(g.a)} v ${side(g.b)}`;
      if (g.id === 'decider') {
        w(`| ${s.slot} | ${s.time} | ${g.court} | ${label} | ${BLANK} | ${SCORE} | | | |`);
        w(`| | | | *only if the losers' bracket team won the Final* | ${BLANK} | ${SCORE} | | | |`);
        continue;
      }
      w(`| ${s.slot} | ${s.time} | ${g.court} | ${label} | ${BLANK} | ${SCORE} | ${SCORE} | ${SCORE} | ${SCORE} |`);
      w(`| | | | | ${BLANK} | ${SCORE} | ${SCORE} | ${SCORE} | ${SCORE} |`);
    }
  }
  w();
  w(`Bracket matches: **best of ${bracket.bestOf}**. Games to ${bracket.to}, win by ${bracket.winBy}, ` +
    `cap ${bracket.cap}; a third game goes to ${bracket.lastTo}, cap ${bracket.lastCap}. ` +
    'On the website, enter **games won** (2-0 or 2-1), not points.');
} else {
  w('| Slot | Time | Court | Game | Team A | Score | Team B | Score |');
  w('|:--|:--|:--:|:--|:--|:--:|:--|:--:|');
  for (const s of schedule.slots.filter((x) => x.phase === 'bracket')) {
    for (const g of s.games) {
      const label = `**${g.label}** — ${side(g.a)} v ${side(g.b)}`;
      w(`| ${s.slot} | ${s.time} | ${g.court} | ${label} | ${BLANK} | ${SCORE} | ${BLANK} | ${SCORE} |`);
    }
  }
  w();
  w(`Bracket games: **to ${bracket.to}**, win by ${bracket.winBy}, cap ${bracket.cap}.`);
}
w();
if (teams.length > 4) {
  w(
    `Seeds #5-#${teams.length} finish on pool record — there is no slot for a placement game below ` +
      'the top four.'
  );
  w();
}
w('---');
w();
w('## Champion');
w();
w('# ________________________________');
w();
w('**2nd:** ____________________  **3rd:** ____________________');
w();

writeFileSync(join(root, 'docs/scoresheet.md'), out.join('\n'));
console.log(
  `\n  ✓ Wrote docs/scoresheet.md — ${teams.length} teams, ` +
    `${poolSlots.length} pool slots, ${t.courts} courts\n`
);
