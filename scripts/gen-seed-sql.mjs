#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from data/teams.json + data/schedule.json.
 *
 * The database is seeded from the same JSON the site reads, so the two can't
 * drift. Re-run after editing either file.
 *
 * Run: node scripts/gen-seed-sql.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const { teams } = read('data/teams.json');
const schedule = read('data/schedule.json');

/** Single-quote escape for SQL literals. */
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(', ')}]::text[]`;
const num = (v) => (v === null || v === undefined ? 'null' : String(v));

const out = [];
const w = (s = '') => out.push(s);

w('-- GENERATED by scripts/gen-seed-sql.mjs — do not edit by hand.');
w('-- Regenerate after any change to data/teams.json or data/schedule.json.');
w();
w('begin;');
w();

// Teams -----------------------------------------------------------------------
w('-- Teams. Names only: no emails, no phone numbers.');
for (const t of teams) {
  w(
    `insert into public.teams (id, name, seed, captain, players, roster_pending, has_net, color_a, color_b, blurb) values (\n` +
      `  ${q(t.id)}, ${q(t.name)}, ${num(t.seed)}, ${q(t.captain)}, ${arr(t.players)},\n` +
      `  ${num(t.rosterPending ?? 0)}, ${t.hasNet ? 'true' : 'false'}, ${q(t.colorA)}, ${q(t.colorB)}, ${q(t.blurb)}\n` +
      `) on conflict (id) do update set\n` +
      `  name = excluded.name, seed = excluded.seed, captain = excluded.captain,\n` +
      `  players = excluded.players, roster_pending = excluded.roster_pending,\n` +
      `  has_net = excluded.has_net, color_a = excluded.color_a,\n` +
      `  color_b = excluded.color_b, blurb = excluded.blurb;`
  );
}
w();

// Games -----------------------------------------------------------------------
// Pool games first: bracket rows have FKs pointing at semifinal ids.
w('-- Games. Scores stay null until a captain submits them.');
const rows = [];
for (const slot of schedule.slots) {
  for (const g of slot.games) {
    const sideRef = (s, key) => (typeof s === 'object' && s?.[key] ? q(s[key]) : 'null');
    const sideSeed = (s) => (typeof s === 'object' && s?.seed ? num(s.seed) : 'null');
    rows.push({
      phase: slot.phase,
      sql:
        `insert into public.games (id, slot, phase, court, start_time, label, team_a, team_b, ref_team, a_seed, b_seed, a_winner_of, b_winner_of, a_loser_of, b_loser_of) values (\n` +
        `  ${q(g.id)}, ${num(slot.slot)}, ${q(slot.phase)}, ${num(g.court)}, ${q(slot.time)}, ${q(g.label ?? null)},\n` +
        `  ${typeof g.a === 'string' ? q(g.a) : 'null'}, ${typeof g.b === 'string' ? q(g.b) : 'null'}, ${q(g.ref ?? null)},\n` +
        `  ${sideSeed(g.a)}, ${sideSeed(g.b)},\n` +
        `  ${sideRef(g.a, 'winnerOf')}, ${sideRef(g.b, 'winnerOf')},\n` +
        `  ${sideRef(g.a, 'loserOf')}, ${sideRef(g.b, 'loserOf')}\n` +
        `) on conflict (id) do update set\n` +
        `  slot = excluded.slot, phase = excluded.phase, court = excluded.court,\n` +
        `  start_time = excluded.start_time, label = excluded.label,\n` +
        `  team_a = excluded.team_a, team_b = excluded.team_b, ref_team = excluded.ref_team,\n` +
        `  a_seed = excluded.a_seed, b_seed = excluded.b_seed,\n` +
        `  a_winner_of = excluded.a_winner_of, b_winner_of = excluded.b_winner_of,\n` +
        `  a_loser_of = excluded.a_loser_of, b_loser_of = excluded.b_loser_of;`,
    });
  }
}
for (const r of rows.filter((x) => x.phase === 'pool')) w(r.sql);
w();
w('-- Bracket rows reference semifinal ids, so they must land after the pool rows.');
for (const r of rows.filter((x) => x.phase === 'bracket')) w(r.sql);
w();
w('commit;');
w();

const sql = out.join('\n');

// Written twice on purpose:
//  - seed.sql            for local `supabase db reset`, and for pasting into the
//                        dashboard SQL editor when rosters change after launch
//  - migrations/…_seed   so first-time setup is a single `supabase db push`
//
// Every statement is an idempotent upsert, so re-running either is safe.
writeFileSync(join(root, 'supabase/seed.sql'), sql);
writeFileSync(join(root, 'supabase/migrations/20260813000001_seed_tournament_data.sql'), sql);

console.log(`  ✓ Wrote supabase/seed.sql — ${teams.length} teams, ${rows.length} games`);
console.log('  ✓ Wrote supabase/migrations/20260813000001_seed_tournament_data.sql');
console.log('\n  Note: if rosters change after the migration has been applied, paste');
console.log('  supabase/seed.sql into the dashboard SQL editor — db push only runs new migrations.');
