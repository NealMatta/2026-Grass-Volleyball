#!/usr/bin/env node
/**
 * Generates docs/SCHEDULE.md from data/schedule.json + data/teams.json.
 *
 * The schedule doc is generated rather than hand-written so it cannot drift out
 * of sync with the data the site actually runs on. Run verify-schedule.mjs
 * first — this script assumes the schedule is already valid.
 *
 * Run: node scripts/gen-schedule-doc.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const { teams } = read('data/teams.json');
const schedule = read('data/schedule.json');
const t = schedule.tournament;

const name = (id) => teams.find((x) => x.id === id)?.name ?? id;
const ids = teams.map((x) => x.id);

const labelOf = (gameId) =>
  schedule.slots.flatMap((s) => s.games).find((g) => g.id === gameId)?.label ?? gameId.toUpperCase();

/** Render a bracket placeholder ({seed:1}, {winnerOf:'sf1'}) as human text. */
const side = (s) => {
  if (typeof s === 'string') return name(s);
  if (s.seed) return `Seed #${s.seed}`;
  if (s.winnerOf) return `Winner of ${labelOf(s.winnerOf)}`;
  if (s.loserOf) return `Loser of ${labelOf(s.loserOf)}`;
  return '?';
};

const out = [];
const w = (s = '') => out.push(s);

/** Minutes between consecutive pool slots, read off the schedule itself. */
const slotGap = (() => {
  const [a, b] = schedule.slots;
  const mins = (t) => { const [h, m] = t.split(':').map(Number); return (h < 8 ? h + 12 : h) * 60 + m; };
  return mins(b.time) - mins(a.time);
})();
const SLOT_GAP = slotGap;

w('<!-- GENERATED by scripts/gen-schedule-doc.mjs — do not edit by hand. -->');
w('<!-- Edit data/schedule.json, run verify-schedule.mjs, then regenerate.  -->');
w();
w('# Schedule');
w();
const prettyDate = new Date(`${t.date}T12:00:00`).toLocaleDateString('en-US', {
  month: 'long',
  day: 'numeric',
  year: 'numeric',
});
w(`**${t.dayOfWeek}, ${prettyDate} · ${t.startTime}am start**`);
w();
w(`${t.venue} — ${t.address}`);
w(`*${t.venueNote}*`);
w();
w(`[Open in Maps](${t.mapUrl})`);
w();
w(`> ${t.rainPolicy}`);
w();
w('---');
w();

// --- Pool ---------------------------------------------------------------------
w('## Pool play');
w();
w(`Games to **${schedule.gameRules.pool.to}**, win by ${schedule.gameRules.pool.winBy}, ` +
  `cap ${schedule.gameRules.pool.cap}. Slots start ${SLOT_GAP} minutes apart.`);
w();
w('| Slot | Time | Court 1 | Court 2 |');
w('|:--|:--|:--|:--|');
for (const s of schedule.slots.filter((x) => x.phase === 'pool')) {
  const [c1, c2] = [1, 2].map((c) => s.games.find((g) => g.court === c));
  w(
    `| ${s.slot} | ${s.time} | ${name(c1.a)} v ${name(c1.b)} | ` +
      `${name(c2.a)} v ${name(c2.b)} |`
  );
}
w();

// --- Per-team -----------------------------------------------------------------
w('### Per-team');
w();
w('| Team | Your day, slot by slot | Plays | Off | Doesn\'t face |');
w('|:--|:--|:--|:--|:--|');
const poolSlots = schedule.slots.filter((x) => x.phase === 'pool');
for (const id of ids) {
  const plays = poolSlots.filter((s) => s.games.some((g) => g.a === id || g.b === id)).map((s) => s.slot);
  const free = poolSlots.map((s) => s.slot).filter((n) => !plays.includes(n));
  const faced = poolSlots
    .flatMap((s) => s.games)
    .filter((g) => g.a === id || g.b === id)
    .map((g) => (g.a === id ? g.b : g.a));
  const missed = ids.filter((o) => o !== id && !faced.includes(o));
  // Play / off strip, in slot order — the quickest way to read your day.
  const strip = poolSlots
    .map((s) => (plays.includes(s.slot) ? '**P**' : '·'))
    .join(' ');
  w(
    `| ${name(id)} | ${strip} | ${plays.join(', ')} | ` +
      `${free.join(', ')} | ${missed.map(name).join(', ')} |`
  );
}
w();
const poolEach = (poolSlots.flatMap((s) => s.games).length * 2) / ids.length;
w(`**P** = playing · **·** = off. Every team plays ${poolEach} pool games. Games are self-called.`);
w();
if (ids.length > t.courts * 2) {
  w('The schedule is built so nobody grinds: you never play more than two slots back to back, and ' +
    'never sit two slots in a row.');
  w();
}

// --- Break + bracket ----------------------------------------------------------
const breakNote = schedule.slots.find((s) => s.note)?.note;
if (breakNote) {
  w('---');
  w();
  w(`## ${breakNote}`);
  w();
}
w('## Bracket');
w();
const br = schedule.gameRules.bracket;
const allGames = schedule.slots.flatMap((s) => s.games);
const decider = allGames.find((g) => g.id === 'decider');
if (br.bestOf) {
  w(`Every match is **best of ${br.bestOf}**. Games to **${br.to}**, win by ${br.winBy}, cap ${br.cap}; ` +
    `a third game goes to **${br.lastTo}**, cap ${br.lastCap}.`);
} else {
  w(`Games to **${br.to}**, win by ${br.winBy}, cap ${br.cap}.`);
}
w();
w('Seeds come from pool record. The site computes them automatically.');
w();
if (allGames.some((g) => g.id === 'wf')) {
  w("**Double elimination.** Lose once and you drop to the losers' bracket; lose twice and you're out.");
  w();
}
if (decider) {
  const d = schedule.gameRules.decider;
  w(`**${decider.label}** — only played if the team from the losers' bracket wins the final. That is the ` +
    `winners' bracket team's first loss, so they play one more game to ${d.to} (cap ${d.cap}) for the title.`);
  w();
}
w('| Slot | Time | Court 1 | Court 2 |');
w('|:--|:--|:--|:--|');
for (const s of schedule.slots.filter((x) => x.phase === 'bracket')) {
  const [c1, c2] = [1, 2].map((c) => s.games.find((g) => g.court === c));
  const cell = (g) => (g ? `**${g.label}** — ${side(g.a)} v ${side(g.b)}` : '—');
  w(`| ${s.slot} | ${s.time} | ${cell(c1)} | ${cell(c2)} |`);
}
w();

/** Schedule times are 12-hour with no meridiem; anything before 8 is PM. */
const toMinutes = (hhmm) => {
  const [h, m] = hhmm.split(':').map(Number);
  return (h < 8 ? h + 12 : h) * 60 + m;
};
const fmt = (mins) => {
  const h24 = Math.floor(mins / 60) % 24;
  const h12 = h24 % 12 === 0 ? 12 : h24 % 12;
  return `${h12}:${String(mins % 60).padStart(2, '0')}${h24 < 12 ? 'am' : 'pm'}`;
};

const lastSlot = schedule.slots[schedule.slots.length - 1];
const startMins = toMinutes(schedule.slots[0].time);
const lastRules = lastSlot.games.some((g) => g.id === 'decider') ? schedule.gameRules.decider : br;
const endMins = toMinutes(lastSlot.time) + lastRules.slotMinutes;
const totalH = Math.floor((endMins - startMins) / 60);
const totalM = (endMins - startMins) % 60;
w(`Finishes by **${fmt(endMins)}** — ${totalH}h${totalM > 0 ? `${totalM}m` : ''} start to finish` +
  `${decider ? `, or ${fmt(toMinutes(lastSlot.time))} if the deciding game isn't needed` : ''}. ` +
  `${br.bestOf ? 'Bracket times assume every match goes three games; start the next one as soon as both teams are free.' : ''}`);
w();
w('---');
w();
w('## Tiebreakers');
w();
schedule.tiebreakers.forEach((tb, i) => w(`${i + 1}. ${tb}`));
w();
w('Steps 1–4 are computed by the site. If two teams are still level after all four, the site says so ' +
  'and it goes to rock paper scissors between captains.');
w();

writeFileSync(join(root, 'docs/SCHEDULE.md'), out.join('\n'));
console.log('  ✓ Wrote docs/SCHEDULE.md');
